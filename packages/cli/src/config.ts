import { applyEdits, type JSONPath, modify, parse } from "jsonc-parser";
import { type Answers, domainOf, resourceNames } from "./answers";

export interface Resources {
  d1Id?: string;
  hyperdriveId?: string;
}

const FORMAT = { formattingOptions: { insertSpaces: true, tabSize: 2, eol: "\n" } };

/**
 * Render a deploy config from the repo's wrangler.jsonc template. jsonc-parser edits in place, so the
 * template's comments survive and users can read what each setting does.
 */
export function renderConfig(template: string, a: Answers & { addresses?: string[] }, r: Resources): string {
  const names = resourceNames(a);
  let text = template;
  const set = (path: JSONPath, value: unknown) => {
    text = applyEdits(text, modify(text, path, value, FORMAT));
  };

  set(["name"], a.workerName);
  set(["account_id"], a.accountId);
  set(["addresses"], a.addresses ?? [a.address.toLowerCase()]);
  set(["workflows", 0, "name"], names.workflow);
  set(["r2_buckets", 0, "bucket_name"], names.bucket);
  set(["define", "__HELPDESK_DB_DRIVER__"], JSON.stringify(a.db));
  set(["vars", "DB_DRIVER"], a.db);
  set(["vars", "ACK_MODE"], a.ackMode);
  set(["vars", "DEFAULT_REF_PREFIX"], a.refPrefix);

  if (a.db === "d1") {
    if (!r.d1Id) throw new Error("renderConfig: D1 database id missing");
    set(["d1_databases", 0, "database_name"], names.d1);
    set(["d1_databases", 0, "database_id"], r.d1Id);
  } else {
    set(["d1_databases"], undefined);
    if (a.db === "postgres" || a.db === "mysql") {
      if (!r.hyperdriveId) throw new Error("renderConfig: Hyperdrive id missing");
      set(["hyperdrive"], [{ binding: "HYPERDRIVE", id: r.hyperdriveId }]);
    }
  }

  const header =
    `// Generated by \`npm run setup\` for ${a.address} (profile "${a.profile}").\n` +
    `// Deploy: npx wrangler deploy -c wrangler.${a.profile}.jsonc   Re-run setup to change it.\n` +
    `// Domain: ${domainOf(a.address)}\n`;
  return header + text;
}

/** Parse a rendered config back (used by tests and re-runs). */
export const readConfig = (text: string) => parse(text, [], { allowTrailingComma: true }) as Record<string, any>;
