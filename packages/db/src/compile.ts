import {
  DummyDriver,
  Kysely,
  MysqlAdapter,
  MysqlIntrospector,
  MysqlQueryCompiler,
  PostgresAdapter,
  PostgresIntrospector,
  PostgresQueryCompiler,
  SqliteAdapter,
  SqliteIntrospector,
  SqliteQueryCompiler,
} from "kysely";
import { migrations } from "./migrations";
import type { SqlDialect } from "./types";

/** A Kysely instance that can only compile SQL (no connection). */
export function compilerFor(d: SqlDialect): Kysely<unknown> {
  const parts = {
    sqlite: [SqliteAdapter, SqliteQueryCompiler, SqliteIntrospector],
    postgres: [PostgresAdapter, PostgresQueryCompiler, PostgresIntrospector],
    mysql: [MysqlAdapter, MysqlQueryCompiler, MysqlIntrospector],
  } as const;
  const [Adapter, Compiler, Introspector] = parts[d];
  return new Kysely<unknown>({
    dialect: {
      createAdapter: () => new Adapter(),
      createDriver: () => new DummyDriver(),
      createQueryCompiler: () => new Compiler(),
      createIntrospector: (db) => new Introspector(db),
    },
  });
}

/** Compile every migration to dialect-specific SQL statements. */
export function compileMigrations(d: SqlDialect): { name: string; statements: string[] }[] {
  const db = compilerFor(d);
  return migrations.map((m) => ({
    name: m.name,
    statements: m.up(db, d).map((q) => q.compile().sql),
  }));
}

export function renderMigrationFile(d: SqlDialect, name: string, statements: string[]): string {
  return (
    `-- Generated by packages/db/scripts/generate.ts from src/migrations/${name}.ts (${d}).\n` +
    `-- Do not edit by hand: change the TypeScript migration and run \`npm run db:generate\`.\n\n` +
    statements.map((s) => `${s};`).join("\n\n") +
    "\n"
  );
}
