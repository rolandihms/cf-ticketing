import type { ColumnDefinitionNode, CreateIndexNode, CreateTableNode, AlterTableNode, OperationNode } from "kysely";
import { compilerFor } from "./compile";
import { MIGRATIONS_TABLE } from "./migrate";
import { type MigrationDef, migrations } from "./migrations";
import { validateTablePrefix } from "./prefix";

/**
 * Prisma models for the help desk tables, so a host app that manages its schema with Prisma
 * (`prisma db push`, `migrate dev`) sees them as its own and never drops them (docs/EMBEDDING.md).
 *
 * Built from the same migration definitions as the SQL, so the two can't drift: column types,
 * nullability, primary keys, unique constraints and index names match what MySQL actually has, and
 * `prisma migrate diff` against a migrated database is empty (tested in CI).
 *
 * MySQL only for now (the help desk declares no foreign keys there; with Postgres FKs, Prisma would
 * want relations).
 */
export function renderPrismaSchema(opts: { tablePrefix?: string; modelPrefix?: string; /** for tests */ migrations?: MigrationDef[] } = {}): string {
  const defs = opts.migrations ?? migrations;
  const prefix = validateTablePrefix(opts.tablePrefix);
  const modelPrefix = opts.modelPrefix ?? (prefix ? pascal(prefix) : "Helpdesk");
  const tables = collectTables(defs);

  const out: string[] = [
    "// Generated by cf-helpdesk from its migrations (" + defs.at(-1)!.name + `, table prefix "${prefix}"). Do not edit:`,
    "// re-run `cf-helpdesk init` after upgrading. Read-only from Prisma: write through the help desk API,",
    "// which keeps ticket numbers, events and email threading consistent.",
  ];
  for (const t of tables.values()) {
    const fields = t.columns.map((c) => {
      const { type, attrs } = prismaType(c.type);
      const fieldAttrs = [...(c.primaryKey ? ["@id"] : []), ...(c.unique ? [`@unique(map: "${c.name}")`] : []), ...attrs];
      return [c.name, `${type}${c.notNull || c.primaryKey ? "" : "?"}`, fieldAttrs.join(" ")];
    });
    const widths = [0, 1].map((i) => Math.max(...fields.map((f) => f[i]!.length)));
    const block = fields.map((f) => `  ${f[0]!.padEnd(widths[0]!)} ${f[1]!.padEnd(widths[1]!)} ${f[2]}`.trimEnd());
    for (const pk of t.compositePk) block.push(`  @@id([${pk.join(", ")}])`);
    for (const u of t.uniques) block.push(`  @@unique([${u.columns.join(", ")}], map: "${prefix}${u.name}")`);
    for (const i of t.indexes) block.push(`  @@index([${i.columns.join(", ")}], map: "${prefix}${i.name}")`);
    block.push(`  @@map("${prefix}${t.name}")`);
    out.push("", `model ${modelPrefix}${pascal(t.name)} {`, ...block, "}");
  }
  return out.join("\n") + "\n";
}

interface Column {
  name: string;
  type: string;
  notNull: boolean;
  primaryKey: boolean;
  unique: boolean;
}

interface Table {
  name: string;
  columns: Column[];
  compositePk: string[][];
  uniques: { name: string; columns: string[] }[];
  indexes: { name: string; columns: string[] }[];
}

const ident = (n: OperationNode | undefined): string => {
  const x = n as { kind: string; name?: string; column?: OperationNode; table?: OperationNode; identifier?: OperationNode } | undefined;
  if (!x) throw new Error("renderPrismaSchema: missing identifier");
  if (x.kind === "IdentifierNode") return x.name!;
  if (x.kind === "ColumnNode") return ident(x.column);
  if (x.kind === "TableNode") return ident(x.table);
  if (x.kind === "SchemableIdentifierNode") return ident(x.identifier);
  throw new Error(`renderPrismaSchema: unexpected ${x.kind}`);
};

function sqlType(n: OperationNode): string {
  if (n.kind === "RawNode") return (n as unknown as { sqlFragments: string[] }).sqlFragments.join("").trim().toLowerCase();
  if (n.kind === "DataTypeNode") return String((n as unknown as { dataType: string }).dataType).toLowerCase();
  throw new Error(`renderPrismaSchema: unsupported column type node ${n.kind}`);
}

/** Column features the models don't express. Refuse them: a silently wrong model makes `db push` alter the table. */
const UNMODELLED = ["defaultTo", "check", "autoIncrement", "generated", "unsigned", "frontModifiers", "endModifiers", "nullsNotDistinct", "identity", "onUpdate"] as const;

function column(def: ColumnDefinitionNode): Column {
  const used = UNMODELLED.filter((k) => {
    const v = (def as unknown as Record<string, unknown>)[k];
    return v !== undefined && v !== false && !(Array.isArray(v) && v.length === 0);
  });
  if (used.length) throw new Error(`renderPrismaSchema: column ${ident(def.column)} uses ${used.join(", ")}, which the Prisma generator doesn't model yet; extend prisma.ts`);
  return { name: ident(def.column), type: sqlType(def.dataType), notNull: !!def.notNull, primaryKey: !!def.primaryKey, unique: !!def.unique };
}

function collectTables(defs: MigrationDef[]): Map<string, Table> {
  const db = compilerFor("mysql");
  const tables = new Map<string, Table>();
  // The bookkeeping table applyMigrations creates (same definition, see migrate.ts).
  tables.set(MIGRATIONS_TABLE, {
    name: MIGRATIONS_TABLE,
    columns: [
      { name: "name", type: "varchar(255)", notNull: true, primaryKey: true, unique: false },
      { name: "applied_at", type: "bigint", notNull: true, primaryKey: false, unique: false },
    ],
    compositePk: [],
    uniques: [],
    indexes: [],
  });
  const get = (name: string) => {
    const t = tables.get(name);
    if (!t) throw new Error(`renderPrismaSchema: table ${name} is altered before it is created`);
    return t;
  };

  for (const m of defs) {
    for (const q of m.up(db, "mysql")) {
      const node = q.toOperationNode();
      if (node.kind === "CreateTableNode") {
        const n = node as CreateTableNode;
        const t: Table = { name: ident(n.table), columns: n.columns.map(column), compositePk: [], uniques: [], indexes: [] };
        for (const c of n.constraints ?? []) {
          const cols = (c as unknown as { columns: OperationNode[] }).columns.map(ident);
          if (c.kind === "PrimaryKeyConstraintNode") t.compositePk.push(cols);
          else if (c.kind === "UniqueConstraintNode") t.uniques.push({ name: ident((c as unknown as { name: OperationNode }).name), columns: cols });
          else throw new Error(`renderPrismaSchema: unsupported constraint ${c.kind}`);
        }
        tables.set(t.name, t);
      } else if (node.kind === "AlterTableNode") {
        const n = node as AlterTableNode;
        const t = get(ident(n.table));
        for (const a of n.columnAlterations ?? []) {
          if (a.kind !== "AddColumnNode") throw new Error(`renderPrismaSchema: unsupported alteration ${a.kind}`);
          t.columns.push(column((a as unknown as { column: ColumnDefinitionNode }).column));
        }
        if (Object.keys(n).some((k) => !["kind", "table", "columnAlterations"].includes(k))) {
          throw new Error(`renderPrismaSchema: unsupported ALTER TABLE in ${m.name}`);
        }
      } else if (node.kind === "CreateIndexNode") {
        const n = node as CreateIndexNode;
        if (n.where || n.using) throw new Error(`renderPrismaSchema: partial or USING indexes (${ident(n.name)}) aren't modelled; extend prisma.ts`);
        const t = get(ident(n.table));
        const entry = { name: ident(n.name), columns: (n.columns ?? []).map(ident) };
        (n.unique ? t.uniques : t.indexes).push(entry);
      } else {
        throw new Error(`renderPrismaSchema: unsupported statement ${node.kind} in ${m.name}`);
      }
    }
  }
  return tables;
}

/** MySQL column type (as the migrations write it) → Prisma scalar + native type attribute. */
function prismaType(sql: string): { type: string; attrs: string[] } {
  const base = sql.replace(/\s+character set.*$/, "");
  let m: RegExpMatchArray | null;
  if ((m = base.match(/^varchar\((\d+)\)$/))) return { type: "String", attrs: [`@db.VarChar(${m[1]})`] };
  if ((m = base.match(/^char\((\d+)\)$/))) return { type: "String", attrs: [`@db.Char(${m[1]})`] };
  if (base === "mediumtext") return { type: "String", attrs: ["@db.MediumText"] };
  if (base === "tinyint") return { type: "Int", attrs: ["@db.TinyInt"] };
  if (base === "integer") return { type: "Int", attrs: [] };
  if (base === "bigint") return { type: "BigInt", attrs: [] };
  throw new Error(`renderPrismaSchema: no Prisma mapping for MySQL type "${sql}"`);
}

/** "hd_" → "Hd", "ticket_events" → "TicketEvents", "_helpdesk_migrations" → "HelpdeskMigrations" */
const pascal = (s: string) =>
  s
    .split("_")
    .filter(Boolean)
    .map((w) => w[0]!.toUpperCase() + w.slice(1))
    .join("");
